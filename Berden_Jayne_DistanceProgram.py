import math
x1 = int(input("Enter your x1: "))
x2 =int(input("Enter your x2: "))
y1 =int(input("Enter your y1: "))
y2 = int(input("Enter your y2: "))

distance = math.sqrt((x2 - x1) **2 + (y2 - y1) **2)
print (f"Your distance is {distance:.2F}")

